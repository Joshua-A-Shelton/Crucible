using System.Globalization;
using System.Runtime.InteropServices;
using System.Text;
using Crucible.Binary;
using Crucible.Importers;
using Crucible.Serialization;
using ImportersApi = Crucible.Importers.Api;

namespace Crucible.Assets.Importers;

/// <summary>A material shader's import settings: none yet.</summary>
[Serialized]
public partial class ShaderImportSettings;

/// <summary>
/// Imports material shaders (ADR 0052): a .slang file compiled for this
/// platform's formats, with entry points for every struct implementing
/// <c>IMaterial</c> and their parameter layouts (the .crshader's MTYP
/// section). Each material type also gets a C# struct in the game's code,
/// <c>Code/Generated/Materials/&lt;Type&gt;.g.cs</c>. Modules it imports from
/// <c>Assets/</c> are dependencies: changing one reimports it.
/// </summary>
public sealed class ShaderImporter : Importer<ShaderImportSettings>
{
    public static readonly uint Kind = Tag.Of("SHDR");
    public const uint KindVersion = 1;
    public const string FileExtension = ".crshader";

    public override string Name => "Shader";

    public override int Version => 1;

    public override IReadOnlyList<string> Extensions => [".slang"];

    public override string OutputExtension => FileExtension;

    /// <summary>
    /// Crucible's shader library (<c>crucible.material</c> and friends),
    /// copied beside the editor's assemblies.
    /// </summary>
    public static string LibraryFolder { get; set; } = Path.Combine(AppContext.BaseDirectory, "shaders");

    // The build's choice (ADR 0047): Windows runs D3D12 and Vulkan, Linux Vulkan.
    private static string Formats => OperatingSystem.IsWindows() ? "dxil,spirv" : "spirv";

    public override void Import(ImportContext context, ShaderImportSettings settings)
    {
        string sourceFolder = Path.GetDirectoryName(context.SourcePath)!;
        string searchPaths = string.Join('\n', sourceFolder, Path.GetFullPath(context.AssetsFolder), LibraryFolder);
        string source = Encoding.UTF8.GetString(context.ReadSource());
        CompiledShaderHandle shader;
        try
        {
            shader = ImportersApi.CompileMaterialShader(context.SourcePath, source, searchPaths, Formats);
        }
        catch (CrucibleException exception) when (exception.Status == Status.InvalidData)
        {
            throw new InvalidDataException(ImportersApi.LastImportError(), exception);
        }
        try
        {
            // Modules it imported from Assets/ (not the library, not itself).
            string assets = Path.GetFullPath(context.AssetsFolder) + Path.DirectorySeparatorChar;
            for (uint i = 0; i < ImportersApi.CompiledDependencyCount(shader); ++i)
            {
                string path = Path.GetFullPath(ImportersApi.CompiledDependency(shader, i));
                if (path.StartsWith(assets, StringComparison.Ordinal) && path != Path.GetFullPath(context.SourcePath))
                {
                    context.ReadDependency(AssetDatabase.AssetPath(context.AssetsFolder, path));
                }
            }
            string warnings = ImportersApi.CompileWarnings(shader);
            if (warnings.Length > 0)
            {
                context.Warn(warnings.TrimEnd());
            }

            ImportedFileWriter output = context.CreateOutput(Kind, KindVersion);
            byte[]? types = null;
            for (uint i = 0; i < ImportersApi.CompiledSectionCount(shader); ++i)
            {
                ShaderSectionInfo info = ImportersApi.CompiledSection(shader, i);
                byte[] bytes = new byte[info.Size];
                ImportersApi.CopyCompiledSection(shader, i, bytes);
                output.Add(info.Tag, info.Version, bytes);
                if (info.Tag == MaterialTypes.Tag)
                {
                    types = bytes;
                }
            }
            if (types is not null)
            {
                foreach (MaterialTypes.Type type in MaterialTypes.Read(types))
                {
                    context.WriteGeneratedSource($"Generated/Materials/{type.Name}.g.cs",
                        GeneratedType(type, context.Asset, context.AssetPath));
                }
            }
        }
        finally
        {
            ImportersApi.DestroyCompiledShader(shader);
        }
    }

    // The C# struct for a material type: its parameters at their offsets, and
    // the shader's defaults.
    internal static string GeneratedType(MaterialTypes.Type type, AssetId shader, string assetPath)
    {
        StringBuilder text = new();
        text.Append("// <auto-generated>\n")
            .Append("// Generated by Crucible's Shader importer from Assets/").Append(assetPath)
            .Append(" (ADR 0052). Do not edit:\n// reimporting the shader writes it again.\n// </auto-generated>\n\n")
            .Append("using System.Numerics;\nusing System.Runtime.CompilerServices;\nusing System.Runtime.InteropServices;\n")
            .Append("using Crucible.Assets;\nusing Crucible.Render;\n\nnamespace Crucible.Materials;\n\n")
            .Append("/// <summary>The parameters of the material ").Append(type.Name).Append(".</summary>\n")
            .Append("[StructLayout(LayoutKind.Explicit, Size = ").Append(type.Size).Append(")]\n")
            .Append("public partial struct ").Append(type.Name).Append(" : IMaterialData\n{\n")
            .Append("    public static AssetId ShaderId { get; } = AssetId.Parse(\"").Append(shader).Append("\");\n\n")
            .Append("    public static string TypeName => \"").Append(type.Name).Append("\";\n\n");
        StringBuilder arrays = new();
        foreach (MaterialTypes.Parameter parameter in type.Parameters)
        {
            string field = Pascal(parameter.Name);
            string element = ElementType(parameter);
            string fieldType = element;
            if (parameter.ArrayLength > 0)
            {
                if (parameter.ArrayStride != ElementSize(parameter))
                {
                    throw new InvalidDataException(
                        $"{type.Name}.{parameter.Name}: arrays whose elements are padded can't be mirrored in C#");
                }
                fieldType = type.Name + field + "Array";
                arrays.Append("/// <summary>The storage of ").Append(type.Name).Append('.').Append(field)
                    .Append("; index it like a span.</summary>\n")
                    .Append("[InlineArray(").Append(parameter.ArrayLength).Append(")]\n")
                    .Append("public struct ").Append(fieldType).Append("\n{\n    private ").Append(element)
                    .Append(" _element0;\n}\n\n");
            }
            text.Append("    [FieldOffset(").Append(parameter.Offset).Append(")] public ").Append(fieldType).Append(' ')
                .Append(field).Append(";\n");
        }

        // Defaults, as the shader's field initializers set them.
        text.Append("\n    /// <summary>The shader's defaults: its field initializers, zero elsewhere.</summary>\n")
            .Append("    public static ").Append(type.Name).Append(" Defaults\n    {\n        get\n        {\n")
            .Append("            ").Append(type.Name).Append(" value = default;\n");
        foreach (MaterialTypes.Parameter parameter in type.Parameters)
        {
            int count = Math.Max(1, (int)parameter.ArrayLength);
            for (int e = 0; e < count; ++e)
            {
                ReadOnlySpan<byte> bytes = type.Defaults.AsSpan((int)(parameter.Offset + e * parameter.ArrayStride),
                    (int)ElementSize(parameter));
                if (bytes.IndexOfAnyExcept((byte)0) < 0)
                {
                    continue;
                }
                string target = "value." + Pascal(parameter.Name) + (parameter.ArrayLength > 0 ? $"[{e}]" : "");
                text.Append("            ").Append(target).Append(" = ").Append(Literal(parameter, bytes)).Append(";\n");
            }
        }
        text.Append("            return value;\n        }\n    }\n}\n");
        if (arrays.Length > 0)
        {
            text.Append('\n').Append(arrays.ToString().TrimEnd('\n')).Append('\n');
        }
        return text.ToString();
    }

    private static string Pascal(string name) => name.Length == 0 ? name : char.ToUpperInvariant(name[0]) + name[1..];

    private static uint ElementSize(MaterialTypes.Parameter parameter) =>
        parameter.Kind == MaterialParameterKind.Texture ? 4 : parameter.Rows * parameter.Columns * 4;

    private static string ElementType(MaterialTypes.Parameter parameter) => parameter.Kind switch
    {
        MaterialParameterKind.Texture => "TextureSlot",
        MaterialParameterKind.Int => "int",
        MaterialParameterKind.Uint => "uint",
        _ when parameter.Rows == 4 => "Matrix4x4",
        _ => parameter.Columns switch { 1 => "float", 2 => "Vector2", 3 => "Vector3", _ => "Vector4" },
    };

    private static string Literal(MaterialTypes.Parameter parameter, ReadOnlySpan<byte> bytes)
    {
        switch (parameter.Kind)
        {
            case MaterialParameterKind.Texture:
                return $"new TextureSlot {{ Index = {MemoryMarshal.Read<uint>(bytes)} }}";
            case MaterialParameterKind.Int:
                return MemoryMarshal.Read<int>(bytes).ToString(CultureInfo.InvariantCulture);
            case MaterialParameterKind.Uint:
                return MemoryMarshal.Read<uint>(bytes).ToString(CultureInfo.InvariantCulture) + "u";
        }
        ReadOnlySpan<float> values = MemoryMarshal.Cast<byte, float>(bytes);
        string list = string.Join(", ", values.ToArray().Select(v => v.ToString("R", CultureInfo.InvariantCulture) + "f"));
        return values.Length == 1 ? list : $"new {ElementType(parameter)}({list})";
    }
}

/// <summary>A .crshader's MTYP section (MaterialFile.h), read.</summary>
internal static class MaterialTypes
{
    public static readonly uint Tag = Crucible.Binary.Tag.Of("MTYP");

    public sealed record Parameter(string Name, uint Offset, MaterialParameterKind Kind, uint Rows, uint Columns,
        uint ArrayLength, uint ArrayStride);

    public sealed record Type(string Name, uint Size, Parameter[] Parameters, byte[] Defaults);

    public static unsafe List<Type> Read(ReadOnlySpan<byte> section)
    {
        uint typeCount = MemoryMarshal.Read<uint>(section);
        uint parameterCount = MemoryMarshal.Read<uint>(section[4..]);
        int typesAt = 8;
        int parametersAt = typesAt + (int)typeCount * sizeof(MaterialTypeInfo);
        if (section.Length < parametersAt + (int)parameterCount * sizeof(MaterialParameter))
        {
            throw new InvalidDataException("the shader's material types are cut short");
        }
        ReadOnlySpan<MaterialTypeInfo> infos =
            MemoryMarshal.Cast<byte, MaterialTypeInfo>(section.Slice(typesAt, (int)typeCount * sizeof(MaterialTypeInfo)));
        ReadOnlySpan<MaterialParameter> parameters = MemoryMarshal.Cast<byte, MaterialParameter>(
            section.Slice(parametersAt, (int)parameterCount * sizeof(MaterialParameter)));
        List<Type> types = [];
        foreach (MaterialTypeInfo info in infos)
        {
            Parameter[] fields = new Parameter[info.ParameterCount];
            for (int p = 0; p < fields.Length; ++p)
            {
                MaterialParameter parameter = parameters[(int)info.FirstParameter + p];
                fields[p] = new Parameter(Name(section, parameter.NameOffset, parameter.NameLength), parameter.Offset,
                    parameter.Kind, parameter.Rows, parameter.Columns, parameter.ArrayLength, parameter.ArrayStride);
            }
            types.Add(new Type(Name(section, info.NameOffset, info.NameLength), info.Size, fields,
                section.Slice((int)info.DefaultsOffset, (int)info.Size).ToArray()));
        }
        return types;
    }

    private static string Name(ReadOnlySpan<byte> section, uint offset, uint length) =>
        Encoding.UTF8.GetString(section.Slice((int)offset, (int)length));
}
